CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_key VARCHAR(100) NOT NULL,
    use_yn CHAR(1) NOT NULL DEFAULT 'Y',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uk_users_user_key UNIQUE (user_key),
    CONSTRAINT ck_users_use_yn CHECK (use_yn IN ('Y', 'N'))
);
COMMENT ON TABLE users IS '사용자 정보';
COMMENT ON COLUMN users.user_id IS '사용자 PK';
COMMENT ON COLUMN users.user_key IS '외부에서 전달되는 사용자 식별값';
COMMENT ON COLUMN users.use_yn IS '사용여부(Y/N)';
COMMENT ON COLUMN users.created_at IS '생성일시';
COMMENT ON COLUMN users.updated_at IS '수정일시';
